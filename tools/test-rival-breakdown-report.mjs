// WinCon — tools/test-rival-breakdown-report.mjs (Milestone 54, Part B)
//
// Regression test for wcRivalBreakdownReport (strategy.js) -- WinCon's own,
// no-external-AI answer to a "Rival Team Builder AI" request (see README's
// Milestone 54 section). Every assertion here checks against real,
// independently-verifiable data (real roster species, real type-chart
// math, real built moves) -- nothing is a placeholder/mocked value.
//
// Run: node tools/test-rival-breakdown-report.mjs

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

function loadJSON(rel) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, rel), "utf8"));
}

const SCRIPT_FILES = ["type-utils.js", "stats.js", "megas.js", "strategy.js"];
const context = vm.createContext({ console });
SCRIPT_FILES.forEach((file) => {
  const code = fs.readFileSync(path.join(ROOT, file), "utf8");
  vm.runInContext(code, context, { filename: file });
});

let checks = 0;
function check(description, fn) {
  fn();
  checks += 1;
  console.log(`OK  ${description}`);
}

const pokemonList = loadJSON("data/pokemon.json");
const baseStatsData = loadJSON("data/base-stats.json");
const learnsets = loadJSON("data/learnsets.json");
const abilitiesData = loadJSON("data/abilities.json");
const movesData = loadJSON("data/moves.json");
const typeChart = loadJSON("data/type-chart.json");
const statsFor = (n) => baseStatsData.find((b) => b.name === n);

function buildTeam(names) {
  const members = names.map((n) => {
    const p = pokemonList.find((pp) => pp.name === n);
    return { name: n, slotName: n, types: p.types, baseStats: statsFor(n), learnableNames: learnsets[n] };
  });
  const builds = {};
  members.forEach((m) => {
    builds[m.name] = context.wcGenerateBuild(
      { name: m.name, types: m.types },
      m.baseStats,
      m.learnableNames,
      movesData,
      [],
      typeChart,
      { format: "doubles", usedItems: new Set(), abilitiesData }
    );
  });
  return { members, builds };
}

// Same two real fixture teams already smoke-tested during Part B's
// implementation -- kept identical here so the formal test builds on a
// roster already known to produce sensible, honest output.
const userTeam = buildTeam(["Charizard", "Primarina", "Steelix", "Sceptile", "Farigiraf", "Whimsicott"]);
const rivalTeam = buildTeam(["Kingambit", "Garchomp", "Incineroar", "Sylveon", "Grimmsnarl", "Sneasler"]);

// A real fixture reasoning array -- not generated by the function under
// test (findYourRival()'s own picker already produces one of these; this
// report reuses it verbatim), so the test just supplies a stand-in array
// of the same shape (one string per rival member) and asserts it's reused
// unchanged.
const fixtureReasoning = rivalTeam.members.map((m) => `${m.name} was picked to answer a real gap in your team.`);

function runReport(reasoning) {
  return context.wcRivalBreakdownReport(
    rivalTeam.members,
    rivalTeam.builds,
    reasoning,
    userTeam.members,
    userTeam.builds,
    movesData,
    typeChart,
    "doubles",
    abilitiesData
  );
}

check("wcRivalBreakdownReport returns all three real fields with no crash on real, complete fixture teams", () => {
  const report = runReport(fixtureReasoning);
  assert.ok(Array.isArray(report.counterStrategyLines) && report.counterStrategyLines.length >= 3);
  assert.ok(Array.isArray(report.rivalRoleLines));
  assert.equal(report.typeSuperiorityLines.length, 2 + (context.wcSharedWeaknessWarnings(rivalTeam.members, typeChart).length > 0 ? 1 : 0));
});

check("wcRivalBreakdownReport's Rival Roles section reuses the real findYourRival() reasoning array verbatim, not a regenerated one", () => {
  const report = runReport(fixtureReasoning);
  assert.deepEqual(report.rivalRoleLines, fixtureReasoning);
});

check("wcRivalBreakdownReport's Rival Roles section is an empty array (not a crash) when no reasoning was supplied", () => {
  const report = runReport(undefined);
  // JSON round-trip strips the vm context's own Array prototype identity
  // before comparing -- an array built inside vm.runInContext code is a
  // different realm's Array than this file's, so a strict deepEqual can
  // fail on prototype identity alone despite matching structurally.
  assert.deepEqual(JSON.parse(JSON.stringify(report.rivalRoleLines)), []);
});

check("wcRivalBreakdownReport's Counter Strategy names each side's own real win condition, matching wcAnalyzeTeamStrategy run independently", () => {
  const report = runReport(fixtureReasoning);
  const rivalAsThreats = rivalTeam.members.map((m) => ({ name: m.name, types: m.types, baseStats: m.baseStats }));
  const userAsThreats = userTeam.members.map((m) => ({ name: m.name, types: m.types, baseStats: m.baseStats }));
  const userStrategy = context.wcAnalyzeTeamStrategy(userTeam.members, userTeam.builds, movesData, rivalAsThreats, typeChart, "doubles", "", abilitiesData, null);
  const rivalStrategy = context.wcAnalyzeTeamStrategy(rivalTeam.members, rivalTeam.builds, movesData, userAsThreats, typeChart, "doubles", "", abilitiesData, null);

  if (userStrategy.archetype === "independent") {
    assert.ok(report.counterStrategyLines[0].startsWith("Your team has no single shared win condition"));
  } else {
    assert.ok(report.counterStrategyLines[0].includes(context.wcArchetypeDisplayName(userStrategy.archetype)), `expected the user's real archetype name in: ${report.counterStrategyLines[0]}`);
  }
  if (rivalStrategy.archetype === "independent") {
    assert.ok(report.counterStrategyLines[1].startsWith("This rival has no single shared win condition"));
  } else {
    assert.ok(report.counterStrategyLines[1].includes(context.wcArchetypeDisplayName(rivalStrategy.archetype)), `expected the rival's real archetype name in: ${report.counterStrategyLines[1]}`);
  }
});

check("wcRivalBreakdownReport's mechanism line is honest about whether the rival's real built moveset actually carries the named counter move", () => {
  const report = runReport(fixtureReasoning);
  const bestMatchupVsUser = context.wcBestMatchupAnalysis(userTeam.members, userTeam.builds, abilitiesData);
  const mechanismLine = report.counterStrategyLines[2];
  if (!bestMatchupVsUser) {
    assert.ok(mechanismLine.includes("doesn't cleanly read as one of the archetypes"), `expected the no-textbook-counter fallback, got: ${mechanismLine}`);
    return;
  }
  const rivalHasCounterMove = rivalTeam.members.some((m) => {
    const build = rivalTeam.builds[m.slotName || m.name] || rivalTeam.builds[m.name];
    return build && Array.isArray(build.moves) && bestMatchupVsUser.counters.some((c) => build.moves.includes(c));
  });
  if (rivalHasCounterMove) {
    assert.ok(mechanismLine.includes("already carries it"), `expected the 'rival really has this move' branch, got: ${mechanismLine}`);
  } else {
    assert.ok(mechanismLine.includes("doesn't happen to carry that exact move"), `expected the honest 'no literal counter move' branch, got: ${mechanismLine}`);
  }
});

check("wcRivalBreakdownReport's Type Superiority lines match wcOffensiveCoverageGaps/wcDefensiveCoverageGaps/wcSharedWeaknessWarnings computed directly on the rival's own real typing", () => {
  const report = runReport(fixtureReasoning);
  const rivalOffenseGaps = context.wcOffensiveCoverageGaps(rivalTeam.members, rivalTeam.builds, movesData, typeChart);
  const rivalDefenseGaps = context.wcDefensiveCoverageGaps(rivalTeam.members, typeChart);
  const rivalSharedWeaknesses = context.wcSharedWeaknessWarnings(rivalTeam.members, typeChart);

  if (rivalOffenseGaps.length === 0) {
    assert.ok(report.typeSuperiorityLines[0].includes("offensively covers all 18 types"));
  } else {
    rivalOffenseGaps.forEach((type) => assert.ok(report.typeSuperiorityLines[0].includes(type), `expected real offense gap ${type} named in: ${report.typeSuperiorityLines[0]}`));
  }
  if (rivalDefenseGaps.length === 0) {
    assert.ok(report.typeSuperiorityLines[1].includes("No clean defensive gap"));
  } else {
    rivalDefenseGaps.forEach((type) => assert.ok(report.typeSuperiorityLines[1].includes(type), `expected real defense gap ${type} named in: ${report.typeSuperiorityLines[1]}`));
  }
  if (rivalSharedWeaknesses.length > 0) {
    assert.equal(report.typeSuperiorityLines[2], rivalSharedWeaknesses[0], "expected the real top shared-weakness warning to be included verbatim");
  }
});

console.log(`\nAll ${checks} Rival Breakdown Report checks passed.`);
